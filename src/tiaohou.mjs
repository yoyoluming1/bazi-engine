/**
 * 调候用神。
 * 返回主用/辅助（天干 + 五行）与推导依据；表里没有的组合会明确说「未收录」，
 * 而不是编一个出来。
 */
export function tiaohou({ chart }) {
  const monthZhi = chart.pillars[1].zhi
  const dayGan = chart.dayGan
  const cell = TIAOHOU[monthZhi]?.[dayGan]

  if (!cell) {
    return { available: false, reason: `调候表未收录 ${dayGan} 日生于 ${monthZhi} 月` }
  }

  const gans = [...cell]
  const main = gans[0]
  const assist = gans.slice(1)
  const basis = [
    `月令${monthZhi}，${SEASON[monthZhi]}`,
    `日干${dayGan}（${GAN_ELEM[dayGan]}）`,
    `取${main}为调候主用（${GAN_ELEM[main]}）${assist.length ? `，辅以${assist.join('、')}` : ''}`,
  ]

  // 与扶抑是否同向 —— 这是解释「两个用神打不打架」的关键
  const support = chart.score?.[GAN_ELEM[main]] ?? 0
  if (support > 2) basis.push(`注意：${GAN_ELEM[main]}在盘中已有 ${support}，调候所需与盘面偏多同向，宜节制`)

  return {
    available: true,
    month: monthZhi,
    season: SEASON[monthZhi],
    main,
    assist,
    mainElement: GAN_ELEM[main],
    assistElements: [...new Set(assist.map((g) => GAN_ELEM[g]))],
    elements: [...new Set(gans.map((g) => GAN_ELEM[g]))],
    basis,
  }
}
